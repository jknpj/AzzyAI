//! Translations shared with the web GUI.
//!
//! `tools/webgui-data.js` dumps `webgui/i18n.strings.js` and `webgui/i18n.desc.{pt,es}.js` to
//! `data/i18n.json` (committed and checked for drift in CI), the same file the web GUI uses at
//! runtime. UI strings are keyed by their English text; setting descriptions are keyed by the
//! option name and scoped to `hom`/`mer`. Anything without a translation stays English.
//!
//! The language is process-wide (the GUI is single threaded): `set_lang()` before drawing and
//! `tr()`/`desc()` anywhere. The choice is remembered in a tiny file under `%APPDATA%`
//! (Windows) or `$XDG_CONFIG_HOME`/`$HOME/.config` (elsewhere), so it never touches USER_AI.

use std::collections::HashMap;
use std::path::PathBuf;
use std::cell::Cell;
use std::sync::OnceLock;

use serde_json::Value;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    En,
    Pt,
    Es,
}

impl Lang {
    pub const ALL: [Lang; 3] = [Lang::En, Lang::Pt, Lang::Es];

    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Pt => "pt",
            Lang::Es => "es",
        }
    }

    /// Same labels as the web GUI's language selector.
    pub fn label(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Pt => "Português (BR)",
            Lang::Es => "Español (LatAm)",
        }
    }

    fn from_code(code: &str) -> Option<Lang> {
        match code.trim().to_lowercase().as_str() {
            "en" => Some(Lang::En),
            "pt" | "pt-br" => Some(Lang::Pt),
            "es" | "es-419" => Some(Lang::Es),
            _ => None,
        }
    }

    /// Index into `Tables::strings`/`Tables::desc`; English is the source, with no table.
    fn index(self) -> Option<usize> {
        match self {
            Lang::En => None,
            Lang::Pt => Some(0),
            Lang::Es => Some(1),
        }
    }
}

// The GUI is single threaded, so the language only has to be consistent within the thread that
// draws. Keeping it thread local also keeps `cargo test` honest: every test runs in its own
// thread and calling `set_lang` there used to change the language of the tests running in
// parallel (the description-card tests failed at random).
thread_local! {
    static CURRENT: Cell<Lang> = const { Cell::new(Lang::En) };
}

pub fn lang() -> Lang {
    CURRENT.with(Cell::get)
}

pub fn set_lang(lang: Lang) {
    CURRENT.with(|current| current.set(lang));
}

struct Tables {
    /// [pt, es] dictionaries keyed by the English source text.
    strings: [HashMap<String, String>; 2],
    /// [pt, es] description tables: lang -> scope -> setting name -> text.
    desc: [HashMap<String, HashMap<String, String>>; 2],
}

fn table() -> &'static Tables {
    static TABLES: OnceLock<Tables> = OnceLock::new();
    TABLES.get_or_init(|| {
        let doc: Value = serde_json::from_str(include_str!("../../../webgui/data/i18n.json"))
            .expect("data/i18n.json is generated by tools/webgui-data.js");
        let strings = [
            object_of(doc.pointer("/strings/pt").unwrap_or(&Value::Null)),
            object_of(doc.pointer("/strings/es").unwrap_or(&Value::Null)),
        ];
        let desc = [
            desc_tables(doc.pointer("/desc/pt").unwrap_or(&Value::Null)),
            desc_tables(doc.pointer("/desc/es").unwrap_or(&Value::Null)),
        ];
        Tables { strings, desc }
    })
}

fn desc_tables(value: &Value) -> HashMap<String, HashMap<String, String>> {
    value
        .as_object()
        .map(|map| {
            map.iter()
                .map(|(scope, entries)| (scope.clone(), object_of(entries)))
                .collect()
        })
        .unwrap_or_default()
}

fn object_of(value: &Value) -> HashMap<String, String> {
    value
        .as_object()
        .map(|map| {
            map.iter()
                .filter_map(|(key, text)| text.as_str().map(|text| (key.clone(), text.to_string())))
                .collect()
        })
        .unwrap_or_default()
}

/// Translates UI text; English or an untranslated string is returned unchanged.
pub fn tr(text: &str) -> String {
    tr_args(text, &[])
}

/// Like `tr`, filling `{0}`, `{1}`... placeholders (the web GUI's convention).
pub fn tr_args(text: &str, args: &[&str]) -> String {
    translate(lang(), text, args)
}

fn translate(lang: Lang, text: &str, args: &[&str]) -> String {
    let mut out = match lang.index() {
        Some(slot) => native(slot, text)
            .map(str::to_string)
            .or_else(|| table().strings[slot].get(text).cloned())
            .unwrap_or_else(|| text.to_string()),
        None => text.to_string(),
    };
    for (index, arg) in args.iter().enumerate() {
        out = out.replace(&format!("{{{index}}}"), arg);
    }
    out
}

