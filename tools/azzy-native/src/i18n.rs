fn native(slot: usize, text: &str) -> Option<&'static str> {
    NATIVE
        .iter()
        .find(|(english, _, _)| *english == text)
        .map(|(_, pt, es)| if slot == 0 { *pt } else { *es })
}

/// Translated description of a setting; `scope` is `hom` or `mer`.
pub fn desc(scope: &str, name: &str, english: &str) -> String {
    desc_for(lang(), scope, name, english)
}

fn desc_for(lang: Lang, scope: &str, name: &str, english: &str) -> String {
    match lang.index() {
        Some(slot) => table().desc[slot]
            .get(scope)
            .and_then(|table| table.get(name))
            .cloned()
            .unwrap_or_else(|| english.to_string()),
        None => english.to_string(),
    }
}

// ---------- preference file ----------

fn prefs_path() -> Option<PathBuf> {
    let dir = if cfg!(windows) {
        std::env::var_os("APPDATA").map(PathBuf::from)
    } else {
        std::env::var_os("XDG_CONFIG_HOME")
            .map(PathBuf::from)
            .or_else(|| std::env::var_os("HOME").map(|home| PathBuf::from(home).join(".config")))
    }?;
    Some(dir.join("azzy-native").join("lang"))
}

/// The saved language, the system locale when it is pt/es, or English.
pub fn load_pref() -> Lang {
    if let Some(path) = prefs_path() {
        if let Ok(text) = std::fs::read_to_string(path) {
            if let Some(lang) = Lang::from_code(&text) {
                return lang;
            }
        }
    }
    for name in ["LC_ALL", "LC_MESSAGES", "LANG"] {
        if let Ok(value) = std::env::var(name) {
            if let Some(lang) = Lang::from_code(value.split('.').next().unwrap_or("")) {
                return lang;
            }
        }
    }
    Lang::En
}

/// Best effort: a read-only profile must not stop the GUI from switching language.
pub fn save_pref(lang: Lang) {
    let Some(path) = prefs_path() else { return };
    if let Some(dir) = path.parent() {
        let _ = std::fs::create_dir_all(dir);
    }
    let _ = std::fs::write(path, format!("{}\n", lang.code()));
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn loads_the_web_gui_translations() {
        assert_eq!(
            translate(Lang::Pt, "Apply Settings", &[]),
            "Aplicar configurações"
        );
        assert_eq!(
            translate(Lang::Pt, "Not applied yet", &[]),
            "Ainda não aplicado"
        );
        assert!(desc_for(Lang::Pt, "hom", "AggroHP", "english").starts_with("Seu homúnculo"));
        assert_eq!(
            translate(Lang::Es, "Apply Settings", &[]),
            "Aplicar configuración"
        );
        assert!(desc_for(Lang::Es, "hom", "AggroHP", "english").starts_with("Tu homúnculo"));
        assert_eq!(translate(Lang::En, "Apply Settings", &[]), "Apply Settings");
        assert_eq!(desc_for(Lang::En, "hom", "AggroHP", "english"), "english");
        // a native-only label and a description that has no translation fall back
        assert_eq!(translate(Lang::Pt, "Reload", &[]), "Recarregar");
        assert_eq!(
            desc_for(Lang::Pt, "mer", "NoSuchSetting", "english"),
            "english"
        );
    }

    #[test]
    fn fills_placeholders_and_keeps_unknown_text() {
        assert_eq!(translate(Lang::Pt, "{0} of {1}", &["2", "5"]), "2 de 5");
        assert_eq!(
            translate(Lang::Pt, "native-only text", &[]),
            "native-only text"
        );
        assert_eq!(translate(Lang::En, "{0} of {1}", &["2", "5"]), "2 of 5");
    }
}
