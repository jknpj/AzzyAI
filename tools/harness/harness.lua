function GetActors()
	local r = {}
	for id, e in pairs(world) do if not e.dead then r[#r + 1] = id end end
	table.sort(r)
	return r
end
local selfMonster = false -- scenario option: the client reports our own homunculus as a monster
function IsMonster(id)
	if selfMonster and id == HOMUN then return 1 end
	local e = world[id]; return (e and e.monster) and 1 or 0
end
function GetDistance(x1, y1, x2, y2) return math.floor(math.sqrt((x1 - x2) ^ 2 + (y1 - y2) ^ 2)) end
function IsInAttackSight(a, b, skill, lvl)
	local A, B = world[a], world[b]
	if not A or not B then return false end
	local range = A.atkrange or 1
	if skill and skill ~= 0 then range = math.max(rangeOf(skill, lvl), 1) end
	return math.max(math.abs(A.x - B.x), math.abs(A.y - B.y)) <= range
end

local skillKnown = {}
local getvCalls = {}
function GetV(v, id, extra, extra2)
	getvCalls[v] = (getvCalls[v] or 0) + 1
	local e = world[id]
	if v == V_OWNER then return OWNER end
	if not e then
		if v == V_POSITION then return -1, -1 end
		return 0
	end
	if v == V_POSITION then return e.x, e.y end
	if v == V_TYPE then return e.class or 0 end
	if v == V_MOTION then return e.dead and MOTION_DEAD or (e.motion or MOTION_STAND) end
	if v == V_ATTACKRANGE then return e.atkrange or 1 end
	if v == V_TARGET then return e.target or 0 end
	-- like the client: unknown skills (or levels above the learned one) report range 1
	if v == V_SKILLATTACKRANGE then
		if skillKnown[extra] then return math.max(rangeOf(extra, skillKnown[extra]), 2) end
		return 1
	end
	if v == V_SKILLATTACKRANGE_LEVEL then
		if skillKnown[extra] and (extra2 or 1) <= skillKnown[extra] then return rangeOf(extra, extra2) end
		return 1
	end
	if v == V_HOMUNTYPE then return e.homuntype or e.class end
	if v == V_HP then return e.hp end
	if v == V_SP then return e.sp end
	if v == V_MAXHP then return e.maxhp end
	if v == V_MAXSP then return e.maxsp end
	if v == V_MERTYPE then return e.mertype end
	return 0
end

function Move(id, x, y) local e = world[id]; if e then e.destx, e.desty = x, y; e.motion = MOTION_MOVE end end
function MoveToOwner(id) local o = world[OWNER]; Move(id, o.x, o.y) end
-- the homunculus swings once per ATTACK_DELAY; the swing animation lasts ATTACK_MOTION. Asking for
-- an attack again while it is swinging or waiting changes nothing, like the client.
local ATTACK_DELAY, ATTACK_MOTION = 800, 400
function Attack(id, target)
	local e, t = world[id], world[target]
	if not e then return end
	-- only attacks on real monsters count; anything else (self, owner, players) is a bug
	if t and t.monster then
		e.attacks = (e.attacks or 0) + 1
		if id ~= HOMUN then
			e.motion = MOTION_ATTACK
			t.hitsTaken = (t.hitsTaken or 0) + 1
		elseif now >= (e.nextSwing or 0) then
			e.nextSwing, e.attackUntil = now + ATTACK_DELAY, now + ATTACK_MOTION
			e.motion = MOTION_ATTACK
			t.hitsTaken = (t.hitsTaken or 0) + 1
			HarnessOnHomunAttack(e, t)
		end
	else
		e.badAttacks = (e.badAttacks or 0) + 1; e.badTarget = target
	end
end

-- server-side state that survives AI reloads: cooldowns, buffs and Eleanor's spheres/style/combo
local cooldownUntil, statusUntil = {}, {}
-- rAthena starts Eleanor in fighting style (hom_spawn) and caps spheres at 10 (hom_addspiritball(hd, 10))
local server = { spheres = 0, style = "fighting", combo = nil, comboUntil = 0, sphereHits = 0 }
HarnessServer = server
local MAX_SPHERES = 10
local COMBO_WINDOW = 2000

-- skill.cpp skill_isNotOk_hom; filled in once the AI has defined the skill constants
local ELEANOR_STYLE, ELEANOR_COMBO, EXCLUSIVE, COMBO_SKILLS = {}, {}, {}, {}
local function serverRules()
	ELEANOR_STYLE = {
		[MH_SONIC_CRAW] = "fighting", [MH_SILVERVEIN_RUSH] = "fighting", [MH_MIDNIGHT_FRENZY] = "fighting",
		[MH_TINDER_BREAKER] = "grappling", [MH_CBC] = "grappling", [MH_EQC] = "grappling",
	}
	-- skill -> the skill whose SC_COMBO it needs
	ELEANOR_COMBO = {
		[MH_SILVERVEIN_RUSH] = MH_SONIC_CRAW, [MH_MIDNIGHT_FRENZY] = MH_SILVERVEIN_RUSH,
		[MH_CBC] = MH_TINDER_BREAKER, [MH_EQC] = MH_CBC,
	}
	-- skill_combo: these open a 2 s combo window while at least one sphere is left
	COMBO_SKILLS = { [MH_SONIC_CRAW] = true, [MH_SILVERVEIN_RUSH] = true, [MH_TINDER_BREAKER] = true, [MH_CBC] = true }
	EXCLUSIVE = { [MH_GOLDENE_FERSE] = MH_ANGRIFFS_MODUS, [MH_ANGRIFFS_MODUS] = MH_GOLDENE_FERSE }
end

-- sphere costs: rAthena's on private servers, AzzyAI's official SkillSphereCost (LATAM) otherwise
local function sphereCost(skill, lvl)
	local ra = serverRathena and RA_SKILL and RA_SKILL[skill]
	if ra then return ra.spheres[math.min(lvl, #ra.spheres)] or 0 end
	return (SkillSphereCost and SkillSphereCost[skill]) or 0
end

-- battle.cpp: 50% chance per hit dealt (fighting) or taken (grappling); the harness gives
-- one sphere every second hit so runs stay reproducible
local function sphereHit(style)
	if server.style ~= style then return end
	server.sphereHits = server.sphereHits + 1
	if server.sphereHits % 2 == 0 then server.spheres = math.min(MAX_SPHERES, server.spheres + 1) end
end

-- why the server would refuse this cast, or nil. Everything but range answers "Skill failed";
-- an out-of-range request is dropped silently (unit_skilluse_id2 returns 0)
local function refusal(e, id, kind, skill, lvl, a, b)
	if id ~= HOMUN then return nil end
	if not (skillKnown[skill] and lvl <= skillKnown[skill]) then return "not learned" end
	if cooldownUntil[skill] and now < cooldownUntil[skill] then
		return ("cooldown, %d ms left"):format(cooldownUntil[skill] - now)
	end
	local other = EXCLUSIVE[skill]
	if other and statusUntil[other] and now < statusUntil[other] then
		return "blocked by " .. ((SkillInfo[other] and SkillInfo[other][1]) or tostring(other))
	end
	if e.homuntype == ELEANOR then
		local style = ELEANOR_STYLE[skill]
		if style and style ~= server.style then return "needs " .. style .. " style" end
		local prev = ELEANOR_COMBO[skill]
		if prev and (server.combo ~= prev or now > server.comboUntil) then return "no combo" end
		local cost = sphereCost(skill, lvl)
		if cost > server.spheres then return ("needs %d spheres, has %d"):format(cost, server.spheres) end
	end
	local tx, ty
	if kind == "gnd" then tx, ty = a, b
	elseif a ~= id and world[a] then tx, ty = world[a].x, world[a].y end
	if tx then
		-- battle_check_range: square distance, no tolerance; the homunculus doesn't walk into range.
		-- Range 0 means AzzyAI's official profile doesn't record it (support skills), so it isn't checked.
		local range, dist = rangeOf(skill, lvl), chebyshev(e, { x = tx, y = ty })
		if range > 0 and dist > range then return ("out of range (%d > %d)"):format(dist, range) end
	end
	return nil
end

local function recordCast(kind, id, lvl, skill, a, b)
	local e = world[id]
	local name = (SkillInfo and SkillInfo[skill] and SkillInfo[skill][1]) or tostring(skill)
	local why = refusal(e, id, kind, skill, lvl, a, b)
	-- rAthena skill_check_condition_mercenary: homunculus/mercenary need MORE SP than the cost
	local cost = id == HOMUN and serverField(skill, "sp", lvl) or skillField(skill, 3, lvl)
	local ok = why == nil and e.sp > cost
	if ok then
		e.sp = e.sp - cost
		e.motion = MOTION_SKILL
		local castTime = serverCastTime(skill, lvl)
		local castEnd = now + castTime
		-- the client stops calling AI() while casting and during after-cast delay
		e.busyUntil = castEnd + serverField(skill, "delay", lvl)
		-- rAthena starts the cooldown when the skill goes off (skill_castend_*)
		local cd = serverField(skill, "cooldown", lvl)
		if cd > 0 then cooldownUntil[skill] = castEnd + cd end
		if EXCLUSIVE[skill] then statusUntil[skill] = castEnd + serverField(skill, "duration", lvl) end
		if id == HOMUN and e.homuntype == ELEANOR then
			server.spheres = server.spheres - sphereCost(skill, lvl)
			if skill == MH_BLAZING_AND_FURIOUS then server.spheres = 0 end
			if skill == MH_THE_ONE_FIGHTER_RISES then server.spheres = math.min(MAX_SPHERES, server.spheres + 1) end
			if skill == MH_STYLE_CHANGE then
				server.style = server.style == "fighting" and "grappling" or "fighting"
			end
			if COMBO_SKILLS[skill] and server.spheres > 0 then
				server.combo, server.comboUntil = skill, castEnd + COMBO_WINDOW
			else
				server.combo = nil
			end
			-- skill damage counts as a hit for fighting-style spheres
			if kind == "gnd" or a ~= id then sphereHit("fighting") end
		end
	end
	casts[#casts + 1] = { t = now, kind = kind, skill = skill, name = name, lvl = lvl, a = a, b = b, ok = ok,
		refused = why ~= nil, why = why, sp = e.sp }
end
HarnessCasts = casts
-- refused casts at or after game time t (for checks after an AI reload)
function HarnessRefusedSince(t)
	local n = 0
	for _, c in ipairs(casts) do if c.refused and c.t >= t then n = n + 1 end end
	return n
end
function HarnessMob(id) return world[id] end
function HarnessMonsters()
	local r = {}
	for _, e in pairs(world) do if e.monster then r[#r + 1] = e end end
	return r
end

-- a normal attack by the homunculus landed on monster t
function HarnessOnHomunAttack(h, t)
	-- passive rAthena monsters fight back; plants and other immobile ones never do
	if t.ra and t.target == 0 and not IMMOBILE_AI[t.ra.ai] then
		t.target, t.motion = HOMUN, MOTION_ATTACK
	end
	if h.homuntype == ELEANOR then sphereHit("fighting") end
end
function SkillObject(id, lvl, skill, target) recordCast("obj", id, lvl, skill, target) end
function SkillGround(id, lvl, skill, x, y) recordCast("gnd", id, lvl, skill, x, y) end

