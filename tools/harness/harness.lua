-- Offline test harness for AzzyAI.
-- Simulates the Ragnarok Online client AI API (GetV, GetActors, SkillObject, ...) so the
-- real AI code can run without a game client, then checks the casts against expectations.
--
-- Usage (normally through run.py): lua5.1 harness.lua <scenario> [ticks]
-- The current directory must contain AI/USER_AI, because the AI loads its files by relative path.

local HERE = (arg[0]:match("^(.*)[/\\]") or ".") .. "/"
local scenario = arg[1] or "bayeri"
local TICKS = tonumber(arg[2] or "300")
local STEP = 100 -- ms between AI() calls, like the real client

local now = 1000
local OWNER, HOMUN = 2000001, 2001
local world = {}
local casts = {}
local traces = {}

local function ent(id, t) world[id] = t; t.id = id; return t end

local rangeOf -- defined with the server data below

local function skillField(skill, idx, lvl)
	local si = SkillInfo and SkillInfo[skill]
	if not si then return 0 end
	local c = si[idx]
	if type(c) == "table" then return c[lvl] or c[#c] or 0 end
	return c or 0
end

-- rAthena Renewal data generated by rathena_sync.py (RA_SKILL, RA_HOMUN, RA_MOB)
local haveRathena = pcall(dofile, HERE .. "fixtures/rathena.lua")
if not haveRathena then RA_SKILL, RA_HOMUN, RA_MOB = nil, nil, nil end

-- The simulated server: on private servers (rAthena) its skill data comes from RA_SKILL,
-- on official servers from AzzyAI's own official profile. Set once the scenario is known.
local serverRathena = false
local SKILLINFO_INDEX = { range = 2, sp = 3, fixed = 4, cast = 5, delay = 6, duration = 8, cooldown = 9 }
local function serverField(skill, field, lvl)
	local ra = serverRathena and RA_SKILL and RA_SKILL[skill]
	if ra then
		local list = ra[field]
		if not list then return 0 end
		return list[math.min(lvl or #list, #list)] or 0
	end
	local idx = SKILLINFO_INDEX[field]
	return idx and skillField(skill, idx, lvl) or 0
end
-- time from the request until the skill goes off; variable cast is reduced like the
-- player's CastTimeRatio says it is
local function serverCastTime(skill, lvl)
	return serverField(skill, "fixed", lvl) + math.floor(serverField(skill, "cast", lvl) * (CastTimeRatio or 1))
end
-- the client learns skill ranges from the server, so GetV/IsInAttackSight report the server's
function rangeOf(skill, lvl)
	if not (SkillInfo and SkillInfo[skill]) and not (serverRathena and RA_SKILL and RA_SKILL[skill]) then return 1 end
	local r = serverField(skill, "range", lvl)
	-- rAthena skill_get_range2: negative ranges are relative to the attack range (1)
	if r < 0 then r = -r end
	return r
end
local function chebyshev(a, b) return math.max(math.abs(a.x - b.x), math.abs(a.y - b.y)) end

-- rAthena mob_db Ai codes (doc/mob_db_mode_list.txt)
local AGGRESSIVE_AI = { ["04"] = true, ["05"] = true, ["08"] = true, ["09"] = true, ["10"] = true, ["11"] = true,
	["12"] = true, ["13"] = true, ["19"] = true, ["20"] = true, ["21"] = true, ["26"] = true, ["27"] = true }
local IMMOBILE_AI = { ["06"] = true, ["10"] = true, ["11"] = true }

